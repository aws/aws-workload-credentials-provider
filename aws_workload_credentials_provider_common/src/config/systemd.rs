//! Generates a systemd service override that adds `ReadWriteDirectories` for
//! customer certificate paths, allowing writes through `ProtectSystem=full`.

use std::collections::BTreeSet;
use std::io;
use std::path::{Path, PathBuf};

use super::types::AcmConfig;
use crate::constants::{
    ACM_SERVICE_OVERRIDE_DIR, ACM_SERVICE_OVERRIDE_FILE, PROVIDER_HOME_DIR, PROVIDER_NAME,
};
use crate::filesystem::{FileSystem, RealFileSystem};

/// Generates and installs the systemd drop-in override from ACM configuration.
///
/// Extracts unique parent directories from all configured certificate paths and
/// writes a drop-in that adds them to `ReadWriteDirectories`.
pub fn generate_and_install(acm_config: &AcmConfig) -> io::Result<()> {
    let content = generate_override_content(acm_config)?;
    let fs = RealFileSystem;
    let override_dir = Path::new(ACM_SERVICE_OVERRIDE_DIR);
    std::fs::create_dir_all(override_dir)?;
    let tmp_path = fs.write_string_to_temp(override_dir, &content)?;
    if let Err(e) = fs.atomic_rename(&tmp_path, &override_path()) {
        let _ = fs.remove_file(&tmp_path);
        return Err(e);
    }
    Ok(())
}

/// Generates the content of the systemd drop-in override file.
///
/// Fails if any directory can't be written as a single `ReadWriteDirectories=`
/// token (see [`escape_unit_path`]).
fn generate_override_content(acm_config: &AcmConfig) -> io::Result<String> {
    let mut dirs: BTreeSet<&Path> = BTreeSet::new();

    for cert in acm_config.certificates.values() {
        if let Some(parent) = cert.certificate_path.parent() {
            dirs.insert(parent);
        }
        if let Some(parent) = cert.private_key_path.parent() {
            dirs.insert(parent);
        }
        if let Some(ref chain) = cert.chain_path {
            if let Some(parent) = chain.parent() {
                dirs.insert(parent);
            }
        }
    }

    // Always include the log directory
    let log_dir = Path::new(PROVIDER_HOME_DIR).join("logs");
    dirs.insert(log_dir.as_path());

    let paths_str: String = dirs
        .iter()
        .map(|p| escape_unit_path(p))
        .collect::<io::Result<Vec<_>>>()?
        .join(" ");

    Ok(format!(
        "# Auto-generated by {PROVIDER_NAME} setup-config-based-permissions\n\
         # DO NOT EDIT MANUALLY\n\
         [Service]\n\
         ReadWriteDirectories={paths_str}\n"
    ))
}

/// Encodes a directory as one token of a systemd path-list setting.
///
/// systemd splits the value on whitespace, honours quotes, decodes C-style
/// escapes, then expands `%` specifiers. Each of those characters is escaped
/// so the token decodes back to exactly `path`.
///
/// Control characters are rejected rather than escaped: a newline ends the
/// directive line in the unit file and would let the path inject further
/// `[Service]` directives. Non-UTF-8 paths are rejected because a lossy
/// conversion would grant access to a different directory.
fn escape_unit_path(path: &Path) -> io::Result<String> {
    let s = path.to_str().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("Directory '{}' is not valid UTF-8", path.display()),
        )
    })?;

    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            c if c.is_control() => {
                return Err(io::Error::new(
                    io::ErrorKind::InvalidInput,
                    format!("Directory {s:?} contains a control character"),
                ));
            }
            '\\' => out.push_str("\\\\"),
            ' ' => out.push_str("\\x20"),
            '"' => out.push_str("\\x22"),
            '\'' => out.push_str("\\x27"),
            '%' => out.push_str("%%"),
            c => out.push(c),
        }
    }
    Ok(out)
}

/// Removes the generated drop-in override, if present.
pub fn remove() -> io::Result<()> {
    match std::fs::remove_file(override_path()) {
        Err(e) if e.kind() != io::ErrorKind::NotFound => Err(e),
        _ => Ok(()),
    }
}

/// Returns the full path to the generated override file.
pub fn override_path() -> PathBuf {
    Path::new(ACM_SERVICE_OVERRIDE_DIR).join(ACM_SERVICE_OVERRIDE_FILE)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::types::CertificateConfig;
    use std::collections::HashMap;

    fn make_config(paths: &[(&str, &str, Option<&str>)]) -> AcmConfig {
        let mut certificates = HashMap::new();
        for (i, (cert, key, chain)) in paths.iter().enumerate() {
            certificates.insert(
                format!("arn:aws:acm:us-west-2:123456789012:certificate/test-{i}"),
                CertificateConfig {
                    certificate_arn: format!(
                        "arn:aws:acm:us-west-2:123456789012:certificate/test-{i}"
                    ),
                    certificate_path: PathBuf::from(cert),
                    private_key_path: PathBuf::from(key),
                    chain_path: chain.map(PathBuf::from),
                    refresh_command: Some("/bin/echo reload".to_string()),
                    role_arn: "arn:aws:iam::123456789012:role/Test".to_string(),
                    cert_and_chain_permission: None,
                    key_permission: None,
                    watcher_id: None,
                },
            );
        }
        AcmConfig {
            enabled: true,
            certificates,
            discovery: None,
            ..Default::default()
        }
    }

    #[test]
    fn test_generates_override_with_cert_paths() {
        let config = make_config(&[(
            "/etc/ssl/certs/server.crt",
            "/etc/ssl/private/server.key",
            None,
        )]);
        let content = generate_override_content(&config).unwrap();
        assert!(content.contains("ReadWriteDirectories="));
        assert!(content.contains("/etc/ssl/certs"));
        assert!(content.contains("/etc/ssl/private"));
        assert!(content.contains("/opt/aws/workload-credentials-provider/logs"));
    }

    #[test]
    fn test_deduplicates_paths() {
        let config = make_config(&[(
            "/opt/certs/server.crt",
            "/opt/certs/server.key",
            Some("/opt/certs/chain.pem"),
        )]);
        let content = generate_override_content(&config).unwrap();
        // /opt/certs should appear only once
        let count = content.matches("/opt/certs").count();
        assert_eq!(count, 1);
    }

    #[test]
    fn test_multiple_certificates_different_dirs() {
        let config = make_config(&[
            ("/etc/nginx/certs/a.crt", "/etc/nginx/certs/a.key", None),
            ("/etc/ssl/certs/b.crt", "/etc/ssl/private/b.key", None),
        ]);
        let content = generate_override_content(&config).unwrap();
        assert!(content.contains("/etc/nginx/certs"));
        assert!(content.contains("/etc/ssl/certs"));
        assert!(content.contains("/etc/ssl/private"));
    }

    #[test]
    fn test_rejects_newline_injection_in_directory() {
        let config = make_config(&[(
            "/tmp/holder\nUser=root\nExecStartPre=/tmp/pwn.sh\n#/cert.pem",
            "/etc/ssl/private/server.key",
            None,
        )]);
        let err = generate_override_content(&config).unwrap_err();
        assert_eq!(err.kind(), io::ErrorKind::InvalidInput);
    }

    #[test]
    fn test_escape_unit_path_rejects_control_characters() {
        for dir in ["/a\nb", "/a\rb", "/a\0b", "/a\tb", "/a\u{7f}b", "/a\u{85}b"] {
            let err = escape_unit_path(Path::new(dir)).unwrap_err();
            assert_eq!(err.kind(), io::ErrorKind::InvalidInput, "dir {dir:?}");
        }
    }

    #[cfg(unix)]
    #[test]
    fn test_escape_unit_path_rejects_non_utf8() {
        use std::ffi::OsStr;
        use std::os::unix::ffi::OsStrExt;

        let path = Path::new(OsStr::from_bytes(b"/certs/\xff"));
        let err = escape_unit_path(path).unwrap_err();
        assert_eq!(err.kind(), io::ErrorKind::InvalidInput);
    }

    #[test]
    fn test_escape_unit_path_encodes_systemd_syntax() {
        let cases = [
            ("/etc/ssl/certs", "/etc/ssl/certs"),
            ("/opt/my certs", "/opt/my\\x20certs"),
            ("/opt/a\\x0ab", "/opt/a\\\\x0ab"),
            ("/opt/\"q\"", "/opt/\\x22q\\x22"),
            ("/opt/'q'", "/opt/\\x27q\\x27"),
            ("/opt/%h", "/opt/%%h"),
            ("/opt/a=b#c;d", "/opt/a=b#c;d"),
        ];
        for (input, expected) in cases {
            assert_eq!(
                escape_unit_path(Path::new(input)).unwrap(),
                expected,
                "input {input:?}"
            );
        }
    }

    #[test]
    fn test_override_is_single_directive_line() {
        let config = make_config(&[(
            "/opt/my certs/a.crt",
            "/opt/%h keys/a.key",
            Some("/opt/\"chain\"/c.pem"),
        )]);
        let content = generate_override_content(&config).unwrap();
        let directives: Vec<&str> = content
            .lines()
            .filter(|l| !l.starts_with('#') && !l.is_empty())
            .collect();
        assert_eq!(directives.len(), 2, "{content}");
        assert_eq!(directives[0], "[Service]");
        assert_eq!(
            directives[1],
            "ReadWriteDirectories=/opt/\\x22chain\\x22 /opt/%%h\\x20keys \
             /opt/aws/workload-credentials-provider/logs /opt/my\\x20certs"
        );
    }
}
